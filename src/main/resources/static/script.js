document.addEventListener("DOMContentLoaded", () => {
    const scanBtn = document.getElementById("scanBtn");
    const urlInput = document.getElementById("urlInput");
    const loader = document.getElementById("loader");
    const errorContainer = document.getElementById("errorContainer");
    const errorMessage = document.getElementById("errorMessage");
    const resultsContainer = document.getElementById("resultsContainer");

    scanBtn.addEventListener("click", async () => {
        const url = urlInput.value.trim();

        if (!url) {
            showError("Please enter a valid URL.");
            return;
        }

        // Reset UI states
        hideAll();
        loader.classList.remove("hidden");

        try {
            // Call the Spring Boot Controller endpoint
            const response = await fetch('/api/audit', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json'
                },
                body: JSON.stringify({ url: url })
            });

            const data = await response.json();

            // Handle non-200 responses (Errors generated by our Controller)
            if (!response.ok) {
                // If the backend sent our formatted error JSON, use it. Otherwise, use a generic message.
                const errorText = data.error || `Server error: ${response.status}`;
                showError(errorText);
                return;
            }

            // If successful, render the report
            renderResults(data);

        } catch (err) {
            // Catches network failures (e.g., backend is turned off)
            showError("Failed to connect to the server. Is the backend running?");
            console.error("Network Error:", err);
        }
    });

    function renderResults(data) {
        loader.classList.add("hidden");
        resultsContainer.classList.remove("hidden");

        // Map JSON data to DOM elements
        document.getElementById("resStatus").innerText = data.httpStatus;
        document.getElementById("resTime").innerText = `${data.responseTimeMs} ms`;
        document.getElementById("resH1").innerText = data.h1Count;
        document.getElementById("resImages").innerText = data.imagesMissingAltText;
        document.getElementById("resWords").innerText = data.wordCount;
        
        // Handle potentially null/empty strings gracefully
        document.getElementById("resTitle").innerText = data.pageTitle || "No Title Found";
        document.getElementById("resMeta").innerText = data.metaDescription || "No Meta Description Found";
    }

    function showError(message) {
        loader.classList.add("hidden");
        resultsContainer.classList.add("hidden");
        errorContainer.classList.remove("hidden");
        errorMessage.innerText = message;
    }

    function hideAll() {
        loader.classList.add("hidden");
        errorContainer.classList.add("hidden");
        resultsContainer.classList.add("hidden");
    }
});